"""Deterministic caveat rules for one analysis-grid pixel (EV-02).

The rules turn values already sampled from the L2 products into the ``caveats`` items of
``contracts/schemas/inspect-point.schema.json``. Nothing is generated by an LLM and nothing
is recomputed: slope and layover/shadow come from DT-05, the 50 m edge band from DT-03 and
the AOI rain summary from DT-06. Thresholds and wording are documented in
``docs/methods/caveats.md``.

A caveat warns that something other than fire can explain, distort or blur the observed
radar change at this pixel. It never confirms or rules out fire.
"""

from __future__ import annotations

import math
from collections.abc import Mapping
from dataclasses import dataclass
from datetime import date
from typing import Any, Literal, TypedDict, cast

SLOPE_THRESHOLD_DEG = 30.0
"""Slope above which the steep_slope caveat fires (strictly greater)."""

RAIN_WINDOW_DAYS = 7
"""Last rain day > 1 mm within this many days before the t2 date fires soil_moisture_change."""

RAIN_DAY_MM = 1.0
"""DT-06 rain-day threshold behind ``last_rain_before_t2`` (documentation only)."""

EDGE_BAND_M = 50
"""DT-03 ``perimeter_edge.tif`` band half-width in metres (documentation only)."""

LAYOVER_SHADOW_NONE = 0
LAYOVER_SHADOW_LAYOVER = 1
LAYOVER_SHADOW_SHADOW = 2
LAYOVER_SHADOW_NODATA = 255

CaveatId = Literal[
    "steep_slope",
    "radar_shadow_layover",
    "soil_moisture_change",
    "vegetation_structure",
    "near_perimeter_edge",
]

DataStatus = Literal["mock", "real"]


class Caveat(TypedDict):
    """One item of the inspect-point ``caveats`` array."""

    id: CaveatId
    label: str
    triggered: bool
    reason: str


LABELS: dict[CaveatId, str] = {
    "steep_slope": "Steep slope",
    "radar_shadow_layover": "Radar layover or shadow",
    "soil_moisture_change": "Soil moisture change between dates",
    "vegetation_structure": "Vegetation structure",
    "near_perimeter_edge": "Near the reference perimeter edge",
}

GENERIC_SOIL_MOISTURE_REASON = (
    "Generic caution: moisture changes alter L-band backscatter regardless of fire."
)
GENERIC_VEGETATION_REASON = (
    "Generic caution: HV responds to canopy volume; unburned stand changes also affect it."
)


@dataclass(frozen=True)
class PixelContext:
    """Values sampled at one pixel of the 10 m EPSG:32610 analysis grid.

    ``None`` (or NaN for the slope) means the value is unknown at this pixel.
    """

    valid: bool
    """DT-02 valid mask: all four GCOV inputs finite, positive and not no-data."""
    slope_deg: float | None
    """DT-05 ``slope.tif`` in degrees, 0-90."""
    layover_shadow: int | None
    """DT-05 ``layover_shadow.tif``: 0 none, 1 layover, 2 shadow, 255 no-data."""
    near_perimeter_edge: bool | None
    """DT-03 ``perimeter_edge.tif``: pixel centre within 50 m of the reference boundary."""


@dataclass(frozen=True)
class WeatherSummary:
    """The parts of DT-06 ``weather.json`` the soil-moisture rule needs (AOI-wide)."""

    t2_date: date
    """Date of the 'after' acquisition (``period.end``)."""
    last_rain_before_t2: date | None
    """Last AOI-mean day > 1 mm strictly before t2; ``None`` when there was none."""
    data_status: DataStatus


def weather_summary_from_json(doc: Mapping[str, Any]) -> WeatherSummary | None:
    """Read a ``weather.json`` document (weather.schema.json).

    Returns ``None`` when the optional ``last_rain_before_t2`` field is absent, because the
    rain record is then unknown. An explicit ``null`` means no rain day before t2.

    Field types are checked before any value is used, so a malformed document raises
    ``ValueError`` (or ``KeyError`` for a missing required field), never ``TypeError``.
    """
    data_status = doc.get("data_status")
    if not isinstance(data_status, str) or data_status not in ("mock", "real"):
        raise ValueError(f"weather.json data_status must be 'mock' or 'real', got {data_status!r}")
    period = doc.get("period")
    if not isinstance(period, Mapping):
        raise ValueError(f"weather.json period must be an object, got {period!r}")
    for key in ("start", "end"):
        if not isinstance(period.get(key), str):
            raise ValueError(f"weather.json period.{key} must be a date string")
    t2_date = date.fromisoformat(period["end"])
    if "last_rain_before_t2" not in doc:
        return None
    last = doc["last_rain_before_t2"]
    if last is not None and not isinstance(last, str):
        raise ValueError("weather.json last_rain_before_t2 must be a date string or null")
    return WeatherSummary(
        t2_date=t2_date,
        last_rain_before_t2=date.fromisoformat(last) if last is not None else None,
        data_status=cast(DataStatus, data_status),
    )


def evaluate_caveats(pixel: PixelContext, weather: WeatherSummary | None) -> list[Caveat]:
    """Return the caveats for one pixel, in the contract's enum order.

    An invalid radar pixel has no radar value to qualify, so it gets no caveats. Unknown
    inputs never fire a rule. Out-of-range inputs raise ``ValueError`` rather than being
    silently ignored.
    """
    if not pixel.valid:
        return []

    candidates: list[Caveat | None] = [
        _steep_slope(pixel.slope_deg),
        _radar_shadow_layover(pixel.layover_shadow),
        _soil_moisture_change(weather),
        _caveat("vegetation_structure", triggered=False, reason=GENERIC_VEGETATION_REASON),
        _near_perimeter_edge(pixel.near_perimeter_edge),
    ]
    return [item for item in candidates if item is not None]


def _caveat(caveat_id: CaveatId, *, triggered: bool, reason: str) -> Caveat:
    return {"id": caveat_id, "label": LABELS[caveat_id], "triggered": triggered, "reason": reason}


def _steep_slope(slope_deg: float | None) -> Caveat | None:
    if slope_deg is None or math.isnan(slope_deg):
        return None
    if not 0.0 <= slope_deg <= 90.0:
        raise ValueError(f"slope_deg must be within 0-90 degrees, got {slope_deg}")
    if slope_deg <= SLOPE_THRESHOLD_DEG:
        return None
    reason = (
        f"{_slope_above_threshold(slope_deg)}: steep terrain distorts radar "
        "backscatter (slope from ~30 m GLO-30 DEM, smoothed)."
    )
    return _caveat("steep_slope", triggered=True, reason=reason)


SLOPE_MAX_DECIMALS = 6
"""Most decimals shown for a slope; closer values read 'slope just above 30°'."""


def _slope_above_threshold(slope_deg: float) -> str:
    """Show a slope already known to exceed the threshold without it reading as the threshold.

    Uses the fewest decimals (1 to ``SLOPE_MAX_DECIMALS``) whose shown value is still strictly
    greater than the threshold: 34.24 -> "slope 34.2° > 30°", 30.01 -> "slope 30.01° > 30°".
    A value closer to the threshold than that reads "slope just above 30°".
    """
    threshold = f"{SLOPE_THRESHOLD_DEG:g}°"
    for decimals in range(1, SLOPE_MAX_DECIMALS + 1):
        shown = f"{slope_deg:.{decimals}f}"
        if float(shown) > SLOPE_THRESHOLD_DEG:
            return f"slope {shown}° > {threshold}"
    return f"slope just above {threshold}"


def _radar_shadow_layover(code: int | None) -> Caveat | None:
    if code == LAYOVER_SHADOW_NONE:
        return None
    if code is None or code == LAYOVER_SHADOW_NODATA:
        reason = "Radar geometry unknown at this pixel (no layover/shadow flag available)."
        return _caveat("radar_shadow_layover", triggered=False, reason=reason)
    if code == LAYOVER_SHADOW_LAYOVER:
        what = "layover: the slope facing the sensor is steeper than the incidence angle"
    elif code == LAYOVER_SHADOW_SHADOW:
        what = "shadow: the slope facing away from the sensor hides the ground"
    else:
        raise ValueError(f"layover_shadow must be 0, 1, 2 or 255, got {code}")
    reason = f"Radar {what} (local, approximate flag from DT-05, no ray tracing)."
    return _caveat("radar_shadow_layover", triggered=True, reason=reason)


def _soil_moisture_change(weather: WeatherSummary | None) -> Caveat:
    if weather is None:
        return _caveat("soil_moisture_change", triggered=False, reason=GENERIC_SOIL_MOISTURE_REASON)

    mock = " MOCK weather data." if weather.data_status == "mock" else ""
    last = weather.last_rain_before_t2
    if last is None:
        reason = (
            f"{GENERIC_SOIL_MOISTURE_REASON} AOI-mean rain: no day > {RAIN_DAY_MM:g} mm "
            f"before the after scene ({weather.t2_date.isoformat()}); not per-pixel "
            f"moisture.{mock}"
        )
        return _caveat("soil_moisture_change", triggered=False, reason=reason)

    days_before = (weather.t2_date - last).days
    if days_before < 1:
        raise ValueError(
            f"last_rain_before_t2 {last.isoformat()} must be before t2 "
            f"{weather.t2_date.isoformat()}"
        )
    rain = (
        f"AOI-mean rain > {RAIN_DAY_MM:g} mm last fell on {last.isoformat()}, "
        f"{days_before} day(s) before the after scene"
    )
    if days_before <= RAIN_WINDOW_DAYS:
        reason = (
            f"{rain} (within {RAIN_WINDOW_DAYS} days): wetter soil or canopy can raise "
            f"HH/HV and mask or mimic change. AOI mean, not per-pixel moisture.{mock}"
        )
        return _caveat("soil_moisture_change", triggered=True, reason=reason)
    reason = (
        f"{GENERIC_SOIL_MOISTURE_REASON} {rain} (more than {RAIN_WINDOW_DAYS} days); "
        f"AOI mean, not per-pixel moisture.{mock}"
    )
    return _caveat("soil_moisture_change", triggered=False, reason=reason)


def _near_perimeter_edge(near_edge: bool | None) -> Caveat | None:
    if not near_edge:
        return None
    reason = (
        f"Pixel centre within {EDGE_BAND_M} m of the WFIGS reference boundary: the dated "
        "reference line itself is imprecise here, so inside/outside is uncertain."
    )
    return _caveat("near_perimeter_edge", triggered=True, reason=reason)
